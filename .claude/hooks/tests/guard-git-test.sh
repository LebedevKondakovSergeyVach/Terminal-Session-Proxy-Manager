pass=0; fail=0
for c in "${cases[@]}"; do
  want=${c%%|*}; cmd=${c#*|}
  jq -n --arg c "$cmd" '{tool_name:"Bash",tool_input:{command:$c}}' | "$hook" >/dev/null 2>&1
  rc=$?
  if [ $rc -eq 2 ]; then got=DENY; elif [ $rc -eq 0 ]; then got=ALLOW; else got="ERR$rc"; fi
  if [ "$got" = "$want" ]; then pass=$((pass+1)); else fail=$((fail+1)); printf 'MISMATCH want=%s got=%s :: %q\n' "$want" "$got" "$cmd"; fi
done
echo "pass=$pass fail=$fail"
