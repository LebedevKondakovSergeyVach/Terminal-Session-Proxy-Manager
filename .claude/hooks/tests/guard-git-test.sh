  $'DENY|git commit -m x \\\n  --author="R <r@r>"'
  'DENY|git commit -m "x" --trailer "Co-authored-by=Claude <noreply@anthropic.com>"'
  'DENY|git -C website commit -anm "x"'
  'DENY|git commit -m "Generated with [Claude Code](https://claude.com)"'
  'ALLOW|grep -rn -- --no-verify .githooks'
